type SettingsOperationsMessageKey = keyof typeof germanSettingsOperationsMessages;

const englishSettingsOperationsMessages = Object.fromEntries(
  Object.keys(germanSettingsOperationsMessages).map((message) => [message, message]),
) as { readonly [Key in SettingsOperationsMessageKey]: Key };

export const settingsOperationsMessages = defineDashboardMessages({
  en: englishSettingsOperationsMessages,
  de: germanSettingsOperationsMessages,
  es: spanishSettingsOperationsMessages,
});

export type SettingsOperationsTranslate = (
  key: SettingsOperationsMessageKey,
  variables?: DashboardMessageVariables,
) => string;

export const translateSettingsOperationsMessage = (
  locale: DashboardLocale,
  key: SettingsOperationsMessageKey,
  variables?: DashboardMessageVariables,
): string => translateDashboardMessage(settingsOperationsMessages, locale, key, variables);

export const getSettingsOperationsNumberError = (
  value: number,
  min: number | undefined,
  max: number | undefined,
  t: SettingsOperationsTranslate,
): string | undefined => Number.isFinite(value) && min !== undefined && value < min
  ? t("Use a value of at least {min}.", { min })
  : Number.isFinite(value) && max !== undefined && value > max
    ? t("Use a value no greater than {max}.", { max })
    : undefined;

export const useSettingsOperationsTranslations = (): {
  locale: DashboardLocale;
  t: SettingsOperationsTranslate;
} => {
  let locale: DashboardLocale = "en";
  try {
    locale = useDashboardI18n().locale;
  } catch {
    // Settings controls also render in isolated component tests and previews.
  }
  const t = useCallback<SettingsOperationsTranslate>(
    (key, variables) => translateSettingsOperationsMessage(locale, key, variables),
    [locale],
  );
  return { locale, t };
};
